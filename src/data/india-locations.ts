/** Every state / UT name, in the order shown in the dropdown. */
export const INDIA_STATE_NAMES: readonly string[] = INDIA_LOCATIONS.map(
  (entry) => entry.state,
);

export type IndiaCityOption = {
  readonly city: string;
  readonly state: string;
};

/**
 * Flat city list used when no state has been picked yet, so a student can type
 * "Lucknow" first and have Uttar Pradesh filled in for them.
 */
export const INDIA_CITY_OPTIONS: readonly IndiaCityOption[] =
  INDIA_LOCATIONS.flatMap((entry) =>
    entry.cities.map((city) => ({ city, state: entry.state })),
  );

const CITY_STATES: ReadonlyMap<string, readonly string[]> = (() => {
  const map = new Map<string, string[]>();
  for (const { city, state } of INDIA_CITY_OPTIONS) {
    const key = city.trim().toLowerCase();
    const existing = map.get(key);
    if (existing) {
      if (!existing.includes(state)) existing.push(state);
    } else {
      map.set(key, [state]);
    }
  }
  return map;
})();

export function isKnownIndianState(state: string): boolean {
  return INDIA_STATE_NAMES.includes(state.trim());
}

export function citiesForState(state: string): readonly string[] {
  const key = state.trim();
  return INDIA_LOCATIONS.find((entry) => entry.state === key)?.cities ?? [];
}

/**
 * Which states claim a city name. Empty when unknown (free text is allowed),
 * and longer than one for names shared across states — callers must only
 * auto-fill the state when exactly one comes back.
 */
export function statesForCity(city: string): readonly string[] {
  return CITY_STATES.get(city.trim().toLowerCase()) ?? [];
}
