/**
 * States / Union Territories of India and their cities, backing the structured
 * shipping-address fields on marketplace redemption.
 *
 * Scope and shape
 * ---------------
 * All 36 states and UTs, each with its district headquarters plus the towns
 * large enough that a student would plausibly ship to one. It is deliberately
 * broad but it is NOT the census town list — no fixed list is complete, so the
 * city field accepts free text and this array only drives suggestions. Never
 * reject a city for being absent here.
 *
 * City names are unique within a state. Across states they are not: Aurangabad
 * is in both Maharashtra and Bihar, Hyderabad in Telangana. That is why the
 * reverse lookup (`statesForCity`) returns an array and the UI only auto-fills
 * the state when exactly one state claims the name.
 *
 * Where two towns inside ONE state share a name, the second is disambiguated in
 * parentheses (e.g. Gujarat's "Mandvi" in Kutch vs "Mandvi (Surat)"), because a
 * duplicate string would collide as a React key and read as a dead option.
 */

